"""DS-1 pilot gates (docs/DS1_PROTOCOL.md §7.3, amendment 1): G-b reply validity, G-m composite budget + leading-explanation
check against v5, the A4x-without-scientist = A1e6 equivalence, and the per-episode inference cost of the LLM arms.

Usage: python scripts/ds1_pilot.py --dir artifacts/vm/ds1 --v5-comp artifacts/vm/hdb/artifacts/hdb/s2DC_exp_A1e.jsonl
       [--out experiments/causal_engineer/dev/hdb/ds1/PILOT.md]
"""
from __future__ import annotations

import argparse
import glob
import json
import os

FULL = "FULL_RECOVERY"


def rows(path):
    return [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()]


def shares(r):
    inj = {tuple(x) for x in r["injected_structure"]}
    return any(tuple(x) in inj for x in (r["map_structure"] or []))


def reserve_ok(r):
    """Composite work never pushed the twin's remaining budget below the repair reserve."""
    e = r["engine"]
    reserve = int((e.get("v6") or {}).get("repair_twin_reserve", 1750))
    for ev in e["events"]:
        if ev["kind"] == "composite_expansion" and ev.get("twin_cost", 0) > max(ev["cap"], 0):
            return False
    cap = e["ledger"]["twin"].get("cap", 2800)
    for h in e["history"]:
        if "composite" in h["label"] and cap - h["twin_used"] < reserve:
            return False
    return True


def line(r):
    e = r["engine"]
    nem = r.get("nemotron") or {}
    return (f"| {r['arm']} | `{r['instance_id']}` | {r['verification']['status']} | "
            f"{'+'.join(f'{k}:{t}' for k, t in r['map_structure'] or [])} ({r['map_mass']:.2f}) | "
            f"{'+'.join(f'{k}:{t}' for k, t in r['injected_structure'])} | {e['ledger']['used']} | {e['ledger']['twin']['used']} | "
            f"{sum(1 for x in nem.get('log') or [] if x['status'] == 'ok')}/{len(nem.get('log') or [])} | ${nem.get('cost_usd', 0):.4f} |")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="artifacts/vm/ds1")
    ap.add_argument("--v5-comp", default="artifacts/vm/hdb/artifacts/hdb/s2DC_exp_A1e.jsonl")
    ap.add_argument("--out", default="experiments/causal_engineer/dev/hdb/ds1/PILOT.md")
    a = ap.parse_args()
    pil = {os.path.basename(p): rows(p) for p in sorted(glob.glob(os.path.join(a.dir, "pilot_*.jsonl")))}
    L = ["# DS-1 pilot gates", "", "Init experience bases only. Generated by `scripts/ds1_pilot.py`.", "",
         "| arm | instance | verification | leading explanation (mass) | injected | plant | twin | model calls ok | inference |",
         "|---|---|---|---|---|---|---|---|---|"]
    for name, rs in pil.items():
        if "noscientist" in name:
            continue
        L += [line(r) for r in rs]
    # G-b
    calls = [x for rs in pil.values() for r in rs if r["arm"] in ("A3v5", "A4x") for x in (r.get("nemotron") or {}).get("log") or []]
    ok = sum(1 for x in calls if x["status"] == "ok")
    gb = {"ok": ok, "n": len(calls), "rate": ok / len(calls) if calls else None}
    cost = {arm: [r["nemotron"]["cost_usd"] for rs in pil.values() for r in rs if r["arm"] == arm and r.get("nemotron")]
            for arm in ("A3v5", "A4x")}
    L += ["", "## G-b (reply validity >= 95 %)", "",
          f"- model role calls ok: {ok}/{len(calls)} = {gb['rate']:.1%} -> **{'PASS' if gb['rate'] >= 0.95 else 'FAIL'}**",
          "- inference per episode: " + "; ".join(f"{k} mean ${sum(v) / len(v):.4f} (n {len(v)})" for k, v in cost.items() if v)]
    # equivalence
    eq = pil.get("pilot_A4x_noscientist.jsonl") or []
    ref = {r["instance_id"]: r for r in pil.get("pilot_A1e6.jsonl") or []}
    L += ["", "## Equivalence: A4x with no scientist = A1e6", ""]
    for r in eq:
        b = ref.get(r["instance_id"])
        same = b is not None and all([
            r["verification"] == b["verification"], r["engine"]["ledger"] == b["engine"]["ledger"],
            [d["vector"] for d in r["designs"]] == [d["vector"] for d in b["designs"]],
            r["map_structure"] == b["map_structure"]])
        L.append(f"- `{r['instance_id']}`: verification, plant/twin ledgers, design vectors and leading explanation identical: "
                 f"**{same}**")
    # G-m
    v6c = [r for name, rs in pil.items() if name.endswith(".c.jsonl") and "A1e." not in name for r in rs]
    gm = [r for p in sorted(glob.glob(os.path.join(a.dir, "gm_A1e6.c.jsonl"))) for r in rows(p)]
    v5 = {r["instance_id"]: r for r in rows(a.v5_comp)}
    v5 |= {r["instance_id"]: r for r in pil.get("pilot_A1e.c.jsonl") or []}
    L += ["", "## G-m (composite work within the reserve; leading explanation shares an injected primitive no less often "
          "than v5)", "", f"- reserve respected in {sum(reserve_ok(r) for r in v6c + gm)}/{len(v6c + gm)} v6 composition episodes",
          "", "| instance | v5: shares / FULL / plant | A1e6: shares / FULL / plant | A1e6 composites tried |", "|---|---|---|---|"]
    paired = [(v5[r["instance_id"]], r) for r in gm + [r for r in v6c if r["arm"] == "A1e6"] if r["instance_id"] in v5]
    for x, y in paired:
        L.append(f"| `{y['instance_id']}` | {shares(x)} / {x['verification']['status'] == FULL} / {x['engine']['ledger']['used']} | "
                 f"{shares(y)} / {y['verification']['status'] == FULL} / {y['engine']['ledger']['used']} | "
                 f"{sum(1 for ev in y['engine']['events'] if ev['kind'] == 'composite_expansion')} |")
    s5, s6 = sum(shares(x) for x, _ in paired), sum(shares(y) for _, y in paired)
    f5, f6 = sum(x["verification"]["status"] == FULL for x, _ in paired), sum(y["verification"]["status"] == FULL for _, y in paired)
    L += ["", f"- leading explanation shares an injected primitive: v5 {s5}/{len(paired)}, A1e6 {s6}/{len(paired)} -> "
          f"**{'PASS' if s6 >= s5 else 'FAIL'}**", f"- FULL: v5 {f5}/{len(paired)}, A1e6 {f6}/{len(paired)}"]
    others = [r for r in v6c if r["arm"] != "A1e6"]
    if others:
        L.append("- LLM arms on the pilot composition (descriptive): " + "; ".join(
            f"{r['arm']} shares {shares(r)}" for r in others))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))
    json.dump({"g_b": gb, "g_m": {"v5": s5, "v6": s6, "n": len(paired), "full_v5": f5, "full_v6": f6}},
              open(a.out.replace(".md", ".json"), "w"), indent=1)


if __name__ == "__main__":
    main()
