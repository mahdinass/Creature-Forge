"""X1 (FA-1C, POST-HOC EXPLORATORY): verification of the Phase 1B treatment candidate d3 that candidate selection discarded.

STUDY LABEL: post-hoc and exploratory. The design was chosen AFTER seeing the Phase 1B results; this is not an independent
generalisation test, not a preregistered TA-1 outcome and not evidence for the friction-first policy. One design, one
physical instance (hdb-v1-gen-0073:low_ground_friction:2 = TA-1 case L1), development data only.

Question: does the friction-only candidate d3 (repair:foot_friction, foot_friction 1.9927), which the treatment episode
generated but did not submit (mapped P(FULL) 0.0061 vs 0.0600 for the submitted d4), pass the UNCHANGED full_recovery_v1
verifier on L1's own validation and confirmation seeds? Secondary (descriptive): its paired per-seed distances against the
faulty robot (the Phase 1B robust-seed evidence implied >= 11 of 16 ties within 0.05 m).

Preregistered reading (fixed before execution):
  FULL_RECOVERY        "one candidate generated by the friction-first policy and rejected by stop-map selection passes the
                        frozen verifier on L1" - a demonstrated discarded repair (single design, exploratory); it motivates
                        the selection correction, it does not estimate how often this happens.
  anything else        "no verified recovery for this discarded candidate under the frozen verifier"; on L1 the selection
                        choice between d3 and d4 did not cost a recovery. The preferred next tool-priority experiment then
                        remains L4 (any change to the preregistered Phase 2a order needs explicit documentation and approval).
  in both cases        the paired per-seed table is reported descriptively; no claim about other instances or policies.

What is pinned and checked before any physics (fail-closed):
  * the TA-1 Phase 1B record file (sha256), line, arm, replicate, instance, design index, source, parent and design hash of d3,
    and the hash of the faulty original design 0;
  * d3 lies inside the legal guided body bounds and controller bounds (fault_bench.apply_changes with no change: the exact
    legality check every repair edit passes; no physics);
  * the Phase 1A output (sha256) whose R1 row holds the faulty robot's per-seed validation rows on the same instance;
  * the harness provenance preflight of ta1_tool_access (approved commit = HEAD, clean worktree, implementation ea9e729 with
    unchanged engine/runner/inputs, frozen input hashes, the stored DS-1 record of the same instance);
  * a fresh output and manifest outside every worktree of this repository.
During execution: the rebuilt instance must reproduce the eligibility/fault fields of BOTH the TA-1 record and the stored DS-1
record (else PAUSE before any verification); after verification the faulty robot's 24 per-seed validation rows must equal
Phase 1A's exactly (else the result is written but flagged invalid, PAUSE). The verifier outcome itself never pauses.

Budget: 8 eligibility + 48 validation (24 faulty + 24 candidate) + 48 confirmation-equivalents (24 x 20 s, only if validation
passes) = 104 ten-second rollout-equivalents, local, no twin rollouts, no optimisation.

Usage:
  python scripts/rv2_d3_reverify.py --ta1-record <ta1_phase1b.jsonl> --phase1a-record <rv1_phase1a.jsonl> \\
      --artifacts-root <dir> --records-root <dir>                                                    # dry run (default)
  python scripts/rv2_d3_reverify.py --execute --phase X1 --approved-by "<owner, date>" --harness-commit <40-hex HEAD> \\
      --max-rollouts 104 --ta1-record <...> --phase1a-record <...> --artifacts-root <dir> --records-root <dir> \\
      --out <fresh path outside every worktree>.jsonl
"""
from __future__ import annotations

import argparse
import contextlib
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rv1_reverify as rv1                           # noqa: E402
import ta1_tool_access as ta1                        # noqa: E402

VERSION = "rv2_d3_reverify_v1"
PHASE = "X1"
STUDY = {"id": "FA-1C X1", "label": "post-hoc exploratory verification of a discarded candidate",
         "not": "not an independent generalisation test; not a preregistered TA-1 outcome; not evidence for the policy",
         "design_selected_after_results": True, "n_designs": 1, "n_instances": 1}
L1 = ta1.CASES["L1"]["instance_id"]
# pinned source of the candidate (TA-1 Phase 1B output, FA-1C report of 2026-10-20)
TA1_RECORD = {"file": "ta1_phase1b.jsonl", "sha256": "ebcf29eddbeffdf9b22234180957f25bc8ddd12bd6f6616a607b365c1c5aae67",
              "line": 2, "ta1_arm": "treatment", "replicate": 0, "instance_id": L1, "harness_commit_of_run":
              "33a6e6f05aa0a0af968811156b44755f3c7381f9", "design_index": 3, "design_hash": "84835bc636",
              "source": "repair:foot_friction", "parent": 2, "original_design_hash": "639747be8c"}
# pinned faulty-robot validation rows of the same instance (Phase 1A, row R1)
PHASE1A_RECORD = {"file": "rv1_phase1a.jsonl", "sha256": "0ca0ff3239e525cef02e742425bbe52dd9e2a3fe6bfc66a300ef9810647eb10e",
                  "row_id": "R1", "instance_id": L1}
DS1_RECORD = ta1.CASES["L1"]["stored"][:2]          # ("eval_A1e6_s1.jsonl", 1): stored DS-1 A1e6 record of the same instance
CAP = ta1.ELIGIBILITY_ROLLOUTS + ta1.VERIFY_CAP     # 8 + 96 = 104
TIE_M = 0.05                                        # verdict_v1 tie resolution for walk scores (verdict.DEFAULT_RESOLUTION)


def _line(path: str, line: int) -> dict:
    with open(path, encoding="utf-8") as fh:
        for i, text in enumerate(fh, 1):
            if i == line:
                return json.loads(text)
    raise ValueError(f"{path} has no line {line}")


def resolve_d3(ta1_record_path: str) -> dict:
    """Read d3 from the pinned TA-1 record and check every pinned field (no physics)."""
    problems = []
    got = ta1.sha256_file(ta1_record_path)
    if got != TA1_RECORD["sha256"]:
        return {"problems": [f"TA-1 record sha256 {got} != pinned {TA1_RECORD['sha256']}"]}
    rec = _line(ta1_record_path, TA1_RECORD["line"])
    h = rec.get("harness") or {}
    for key, have in (("instance_id", rec.get("instance_id")), ("ta1_arm", h.get("ta1_arm")), ("replicate", h.get("replicate"))):
        if have != TA1_RECORD[key]:
            problems.append(f"{key} {have!r} != pinned {TA1_RECORD[key]!r}")
    designs = rec.get("designs") or []
    idx = TA1_RECORD["design_index"]
    if len(designs) <= idx:
        return {"problems": problems + [f"record has no design {idx}"]}
    d = designs[idx]
    meta = {m["index"]: m for m in rec["engine"]["ledger"]["designs"]}
    if d.get("index") != idx or d.get("source") != TA1_RECORD["source"] or meta.get(idx, {}).get("parent") != TA1_RECORD["parent"]:
        problems.append(f"design {idx} is {d.get('source')} with parent {meta.get(idx, {}).get('parent')}, not the pinned candidate")
    if ta1.design_hash(d) != TA1_RECORD["design_hash"]:
        problems.append(f"design hash {ta1.design_hash(d)} != pinned {TA1_RECORD['design_hash']}")
    if ta1.design_hash(designs[0]) != TA1_RECORD["original_design_hash"]:
        problems.append(f"original design hash {ta1.design_hash(designs[0])} != pinned {TA1_RECORD['original_design_hash']}")
    if rec.get("submitted") == idx:
        problems.append("d3 was the submitted design; this study is about the discarded candidate")
    return {"record": rec, "design": {"body": d["body"], "vector": d["vector"]}, "problems": problems}


def legality_problems(design: dict) -> list[str]:
    """The guided body bounds and controller bounds every repair edit must satisfy (no change applied; no physics)."""
    from creature_forge.fault_bench import apply_changes
    try:
        apply_changes(design["body"], design["vector"], [])
    except Exception as exc:  # noqa: BLE001 - reported as a refusal, nothing is clipped
        return [f"design outside the legal bounds: {exc}"]
    return []


def resolve_phase1a(path: str) -> dict:
    got = ta1.sha256_file(path)
    if got != PHASE1A_RECORD["sha256"]:
        return {"problems": [f"Phase 1A output sha256 {got} != pinned {PHASE1A_RECORD['sha256']}"]}
    with open(path, encoding="utf-8") as fh:
        rows = [json.loads(x) for x in fh if x.strip()]
    row = next((r for r in rows if r.get("id") == PHASE1A_RECORD["row_id"]), None)
    if row is None or row.get("instance_id") != PHASE1A_RECORD["instance_id"]:
        return {"problems": [f"Phase 1A row {PHASE1A_RECORD['row_id']} for {PHASE1A_RECORD['instance_id']} not found"]}
    return {"row": row, "problems": []}


def faulty_rows_check(full: dict, phase1a_row: dict) -> dict:
    """The verifier re-runs the faulty original on the same validation seeds; it must reproduce Phase 1A's rows exactly."""
    ref = phase1a_row["verification"]["full"]
    checks = {"validate_seeds": full["seeds"]["validate"] == ref["seeds"]["validate"],
              "confirm_seeds": full["seeds"]["confirm"] == ref["seeds"]["confirm"],
              "faulty_rows": ta1.canonical(full["validation"]["original"]) == ta1.canonical(ref["validation"]["original"])}
    return {"exact": all(checks.values()), "checks": checks}


def paired_table(full: dict) -> dict:
    """Per-seed faulty vs candidate validation scores (descriptive; verdict_v1's own statistics are kept in `full`)."""
    rows = []
    for o, c in zip(full["validation"]["original"], full["validation"]["candidate"]):
        if o["seed"] != c["seed"]:
            raise ValueError(f"unpaired seeds {o['seed']} / {c['seed']}")
        diff = None if o["score"] is None or c["score"] is None else c["score"] - o["score"]
        rows.append({"seed": o["seed"], "faulty_score": o["score"], "candidate_score": c["score"], "diff": diff,
                     "tie": diff is not None and abs(diff) <= TIE_M, "faulty_label": o["label"], "candidate_label": c["label"],
                     "candidate_walking": c["walking"], "faulty_walking": o["walking"]})
    d = [r["diff"] for r in rows if r["diff"] is not None]
    vd = full["validation"]["verdict"]
    return {"rows": rows, "n": len(rows), "ties": sum(r["tie"] for r in rows),
            "wins": sum(1 for x in d if x > TIE_M), "losses": sum(1 for x in d if x < -TIE_M),
            "verdict": {k: vd.get(k) for k in ta1.VERDICT_FIELDS}}


def preregistered_reading(status: str) -> str:
    if status == "FULL_RECOVERY":
        return ("one candidate generated by the friction-first policy and rejected by stop-map selection passes the frozen "
                "verifier on L1 (exploratory, single design)")
    return ("no verified recovery for this discarded candidate under the frozen verifier; on L1 the selection between d3 and d4 "
            "did not cost a recovery")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--phase", choices=[PHASE])
    ap.add_argument("--execute", action="store_true")
    ap.add_argument("--approved-by", default="")
    ap.add_argument("--harness-commit", default=None)
    ap.add_argument("--max-rollouts", type=int, default=0)
    ap.add_argument("--ta1-record", default=None, help="the Phase 1B output ta1_phase1b.jsonl")
    ap.add_argument("--phase1a-record", default=None, help="the Phase 1A output rv1_phase1a.jsonl")
    ap.add_argument("--artifacts-root", default=os.path.join(ta1.ROOT, "artifacts", "hdb"))
    ap.add_argument("--records-root", default=os.path.join(ta1.ROOT, "artifacts", "vm", "ds1", "eval"))
    ap.add_argument("--workers", type=int, default=0)
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    inputs = ta1.config_inputs(ta1.ROOT, a.artifacts_root)
    print(f"{VERSION}: {STUDY['label'].upper()} ({STUDY['not']})")
    print(f"  candidate: {TA1_RECORD['file']}#L{TA1_RECORD['line']} {TA1_RECORD['ta1_arm']} r{TA1_RECORD['replicate']} "
          f"{TA1_RECORD['instance_id']} design {TA1_RECORD['design_index']} {TA1_RECORD['design_hash']} ({TA1_RECORD['source']})")
    print(f"  cap {CAP} rollout-equivalents ({ta1.ELIGIBILITY_ROLLOUTS} eligibility + 48 validation + up to 48 confirmation); "
          "no twin rollouts, no optimisation")
    d3 = resolve_d3(a.ta1_record) if a.ta1_record and os.path.isfile(a.ta1_record) else {"problems": ["--ta1-record not found"]}
    p1a = resolve_phase1a(a.phase1a_record) if a.phase1a_record and os.path.isfile(a.phase1a_record) else {"problems": ["--phase1a-record not found"]}
    legal = legality_problems(d3["design"]) if "design" in d3 else []
    pre = ta1.preflight_refusals(ta1.ROOT, inputs, a.records_root, [DS1_RECORD[0]], a.harness_commit)
    checks = d3["problems"] + p1a["problems"] + legal + pre
    for name, p in inputs.items():
        print(f"  input {name}: {p} sha256={ta1.sha256_file(p) or 'MISSING'}")
    if not a.execute:
        print("  pinned-input and preflight checks: " + ("ok" if not checks else "would refuse: " + "; ".join(checks)))
        print("Dry run: nothing was simulated. Pass --execute only with the owner's approval for X1.")
        return 0
    refusals = list(checks)
    if a.phase != PHASE:
        refusals.append(f"--phase {PHASE} is required with --execute")
    if not a.approved_by.strip():
        refusals.append("--approved-by is required with --execute")
    if a.max_rollouts < CAP:
        refusals.append(f"--max-rollouts {a.max_rollouts} is below the cap {CAP}")
    refusals += ta1.output_refusals(a.out, ta1.ROOT)
    missing = [n for n, p in inputs.items() if ta1.sha256_file(p) is None]
    if missing:
        refusals.append(f"missing inputs: {missing}")
    if refusals:
        for r in refusals:
            print("REFUSED:", r)
        return 2
    ds1 = ta1.load_stored(a.records_root, *DS1_RECORD)
    return _execute(a, inputs, d3, ds1, p1a["row"])


def _execute(a, inputs, d3, ds1, p1a_row, *, build_fn=None, verify_fn=None, pool_cm=None) -> int:
    """Fail-closed X1 execution; `build_fn`, `verify_fn` and `pool_cm` are injectable for no-physics tests."""
    if build_fn is None:
        build_fn = ta1.build_instance
    if verify_fn is None:
        from creature_forge import hdb_bench as hb
        verify_fn = hb.verify
    if pool_cm is None:
        from creature_forge.forge_pool import ForgePool, InlinePool
        pool_cm = ForgePool(max_workers=a.workers) if a.workers else contextlib.nullcontext(InlinePool())
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    manifest = ta1.provenance_manifest(ta1.ROOT, inputs, {
        "phase": PHASE, "study": STUDY, "approved_by": a.approved_by, "cap": CAP, "rv2_version": VERSION,
        "harness_commit_approved": a.harness_commit, "ta1_record": {**TA1_RECORD, "path": os.path.abspath(a.ta1_record),
                                                                   "actual_sha256": ta1.sha256_file(a.ta1_record)},
        "phase1a_record": {**PHASE1A_RECORD, "path": os.path.abspath(a.phase1a_record),
                           "actual_sha256": ta1.sha256_file(a.phase1a_record)},
        "ds1_record": {"file": DS1_RECORD[0], "line": DS1_RECORD[1],
                       "sha256": ta1.sha256_file(os.path.join(a.records_root, DS1_RECORD[0]))},
        "preregistered_reading": {"FULL_RECOVERY": preregistered_reading("FULL_RECOVERY"), "other": preregistered_reading("x")}})
    with open(ta1.manifest_path(a.out), "x", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1)
    t0 = time.perf_counter()
    with pool_cm as pool, open(a.out, "x", encoding="utf-8") as out:
        inst = build_fn(L1, inputs, pool=pool)
        ic = rv1.instance_checks(inst, [d3["record"], ds1])
        out.write(json.dumps(ta1.jsonable({"version": VERSION, "kind": "instance_check", "study": STUDY, "instance_id": L1,
                                           "check": inst["check"], "strength": inst.get("strength"), "mult": inst.get("mult"),
                                           "instance_reproduction": ic})) + "\n")
        out.flush()
        if not ic["exact"]:
            return ta1._pause(f"instance {L1} does not reproduce the stored eligibility/fault fields",
                              [k for k, v in ic["checks"].items() if not v])
        orig_hash = ta1.design_hash(inst["robot"])
        if orig_hash != TA1_RECORD["original_design_hash"]:
            return ta1._pause("the rebuilt instance's original design differs from the pinned faulty design", [orig_hash])
        ver = verify_fn(inst, d3["design"], pool=pool)
        sv = ta1.serialize_verification(ver)
        problems = ta1.verification_complete(sv["full"])
        fr = faulty_rows_check(sv["full"], p1a_row) if not problems else {"exact": False, "checks": {}}
        table = paired_table(sv["full"]) if not problems else None
        row = {"version": VERSION, "kind": "design", "study": STUDY, "instance_id": L1, "candidate": TA1_RECORD,
               "design_hash": ta1.design_hash(d3["design"]), "verification": sv, "verification_problems": problems,
               "faulty_rows_vs_phase1a": fr, "paired": table, "preregistered_reading": preregistered_reading(sv["summary"]["status"]),
               "wall_s": time.perf_counter() - t0}
        out.write(json.dumps(ta1.jsonable(row)) + "\n")
        out.flush()
    s = sv["summary"]
    print(f"X1 d3 {s['status']} walking {round(s['walking_frac'] * 24)}/24 | reasons {s['reasons']}")
    if problems or not fr["exact"]:
        return ta1._pause("the X1 record is incomplete or the faulty robot did not reproduce Phase 1A exactly (result flagged invalid)",
                          problems + [k for k, v in fr["checks"].items() if not v])
    print(f"  paired: wins {table['wins']} losses {table['losses']} ties {table['ties']} of {table['n']} | verdict "
          f"{table['verdict']['status']} median {table['verdict']['median_diff']}")
    print("  preregistered reading:", row["preregistered_reading"])
    print("DONE (post-hoc exploratory; one design, one instance).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
