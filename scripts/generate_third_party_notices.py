"""Generate THIRD_PARTY_NOTICES.md from the dependency metadata actually installed/locked (no network).

    .venv\\Scripts\\python scripts\\generate_third_party_notices.py          # writes THIRD_PARTY_NOTICES.md
    .venv\\Scripts\\python scripts\\generate_third_party_notices.py --check  # exit 1 if the committed file is stale

Python packages come from the active environment's installed metadata (direct dependencies and their transitive
requirements); npm packages come from studio/package-lock.json (production vs development). Licenses are reported as
declared by each package; this file is an inventory, not legal advice.
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
PY_ROOTS = ["mujoco", "numpy", "python-dotenv", "fastapi", "uvicorn", "httpx"]       # pyproject dependencies + [studio] extra


def py_closure() -> dict[str, md.Distribution]:
    seen: dict[str, md.Distribution] = {}
    todo = list(PY_ROOTS)
    while todo:
        name = todo.pop()
        try:
            d = md.distribution(name)
        except md.PackageNotFoundError:
            continue
        key = d.metadata["Name"].lower().replace("_", "-")
        if key in seen:
            continue
        seen[key] = d
        for r in d.requires or []:
            if "extra ==" in r:
                continue
            m = re.match(r"[A-Za-z0-9_.\-]+", r)
            if m:
                todo.append(m.group(0))
    return seen


def py_license(d: md.Distribution) -> str:
    m = d.metadata
    lic = m.get("License-Expression") or ""
    if not lic:
        lic = m.get("License") or ""
        if len(lic) > 60 or "\n" in lic:
            lic = ""
    if not lic:
        lic = ", ".join(c.split("::")[-1].strip() for c in m.get_all("Classifier", []) if c.startswith("License")) or "UNKNOWN"
    return lic.strip()


def npm_rows() -> tuple[list, list]:
    lock = json.loads((ROOT / "studio" / "package-lock.json").read_text(encoding="utf-8"))
    prod, dev = [], []
    for path, info in sorted(lock["packages"].items()):
        if not path:
            continue
        name = path.split("node_modules/")[-1]
        lic = info.get("license")
        if not lic:
            pj = ROOT / "studio" / path / "package.json"
            lic = json.loads(pj.read_text(encoding="utf-8")).get("license", "UNKNOWN") if pj.exists() else "UNKNOWN"
            if lic == "UNKNOWN":                                         # no license field: fall back to the package's own LICENSE file
                lf = ROOT / "studio" / path / "LICENSE"
                if lf.exists() and lf.read_text(encoding="utf-8", errors="replace").lstrip().startswith("MIT License"):
                    lic = "MIT (per LICENSE file; no license field in package.json)"
        (dev if info.get("dev") else prod).append((name, info.get("version", ""), lic if isinstance(lic, str) else json.dumps(lic)))
    return prod, dev


def render() -> str:
    py = py_closure()
    prod, dev = npm_rows()
    L = ["# Third-party notices", "",
         "Creature Forge is licensed under the Apache License 2.0 (see `LICENSE`, `NOTICE`). It uses the third-party components below under their own",
         "licenses. This inventory is generated by `scripts/generate_third_party_notices.py` from installed metadata and `studio/package-lock.json`;",
         "licenses are as declared by each package. It is an inventory, not legal advice. Nothing below is bundled in this repository as source: they",
         "are installed by `pip` / `npm`.", "",
         "## External services and models (not redistributed)", "",
         "- **NVIDIA Nemotron** (`nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B`): used only through the Nebius Token Factory API. No model weights are included or",
         "  redistributed. The model's own license/terms (published by NVIDIA) and the Nebius terms apply to its use; this repository grants no rights to them.",
         "- **Nebius AI Cloud / Token Factory**: used as services under Nebius's terms. No Nebius credentials are stored in the repository.",
         "- **MuJoCo** (below) is the physics engine; the robot model is generated by code in `creature_forge/morphology.py`, with no third-party robot assets.",
         "", "## Python packages (runtime closure of the direct dependencies)", "", "| package | version | license |", "|---|---|---|"]
    for k in sorted(py):
        d = py[k]
        L.append(f"| {d.metadata['Name']} | {d.version} | {py_license(d)} |")
    L += ["", f"## npm packages, production ({len(prod)})", "", "| package | version | license |", "|---|---|---|"]
    L += [f"| {n} | {v} | {lic} |" for n, v, lic in prod]
    L += ["", f"## npm packages, development/build tooling only ({len(dev)}; not shipped in `studio/dist` except as compiled by the bundler)", "",
          "| package | version | license |", "|---|---|---|"]
    L += [f"| {n} | {v} | {lic} |" for n, v, lic in dev]
    L += ["", "## Notes", "",
          "- Licenses present: MIT, Apache-2.0, BSD-3-Clause, ISC, MPL-2.0 (build/transitive tooling and `certifi` data only), PSF-2.0, 0BSD, Zlib; all are compatible with distributing this project under Apache-2.0.",
          "- MPL-2.0 packages are used unmodified as separate dependencies; no MPL-covered file is modified or included here.",
          "- Any package showing UNKNOWN must be resolved before a public release.", ""]
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        cur = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if cur != text:
            print("THIRD_PARTY_NOTICES.md is stale; regenerate it")
            sys.exit(1)
        print("THIRD_PARTY_NOTICES.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines); UNKNOWN entries: {text.count('UNKNOWN')}")


if __name__ == "__main__":
    main()
