def cmd_inventory(a) -> None:
    inv = ea.inventory(roots(a), load_split())
    os.makedirs(OUT, exist_ok=True)
    j = ea.json_safe(inv)
    j["morphology_table"] = {b: dict(m) for b, m in sorted(inv["_morph"].items())}     # full precision (provenance checks)
    json.dump(j, open(os.path.join(OUT, "inventory.json"), "w", encoding="utf-8"), indent=1, default=str)
    cols = ["source", "corpus", "kind", "arm", "bench", "iid", "base", "family", "engine", "procedure", "oracle", "tool",
            "status", "full", "plant_used", "twin_used", "replicate"]
    with open(os.path.join(OUT, "outcomes.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(cols + ["generator"])
        for r in sorted(inv["_rows"], key=lambda r: (r["bench"], r["iid"], r["source"], str(r["arm"]))):
            w.writerow([r.get(c) for c in cols] + [ea.generator_group(r["base"])])
    comp = inv["_comp"]
    with open(os.path.join(OUT, "comparability.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["bench", "iid", "base", "level", "engine", "tool", "n_outcomes", "n_full", "informative_at_level"])
        for (bench, iid), lv in sorted(comp.items()):
            for level in ("S", "P", "X"):
                tools = lv[level]
                if len(tools) < 2:
                    continue
                for t, v in sorted(tools.items()):
                    w.writerow([bench, iid, ea.base_of(iid), level, lv["P_engine"] if level == "P" else "", t, len(v), sum(v),
                                ea.informative(tools)])
    open(os.path.join(OUT, "INVENTORY.md"), "w", encoding="utf-8").write(inventory_md(j))
    print(inventory_md(j))


def _t(rows, head) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return out


