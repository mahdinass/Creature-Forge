def cmd_analyse(a) -> None:
    r = roots(a)
    inv = json.load(open(os.path.join(OUT, "inventory.json"), encoding="utf-8"))
    morph = inv["morphology_table"]
    res: dict = {"version": "experience_p0_analysis_v1", "seed": p0.SEED, "n_boot": p0.N_BOOT, "k_grid": p0.K_GRID,
                 "inventory_sha256": ea.sha256_file(os.path.join(OUT, "inventory.json"))}
    gates = inv["gates"]
    res["gates"] = gates
    # ---------------------------------------------------------------- decision analysis on the proxy tier only (D1)
    if gates["CE STANDARDIZED_DEV_PROXY (complete matrix)"]["D1"]:
        probe = ea.rows_of(os.path.join(r["vm"], "ce3/ce/probe_dev.jsonl"))
        res["decision_proxy"] = decision_analysis(probe, morph)
    # HDB decision tiers: none meets D1 -> no predictor is fitted (plan §4); stated in the report from `gates`
    # ---------------------------------------------------------------- HDB diagnostic precondition
    ident = ea.rows_of(os.path.join(r["vm"], "hdb/artifacts/hdb/ident_v2_all.jsonl"))
    res["diagnostic_hdb"] = diagnostic_analysis(ident, morph)
    res["stored_amortized"] = stored_amortized(r)
    res["cited"] = cited_results()
    json.dump(res, open(os.path.join(OUT, "analysis.json"), "w", encoding="utf-8"), indent=1, default=float)
    md = analysis_md(res)
    open(os.path.join(OUT, "ANALYSIS.md"), "w", encoding="utf-8").write(md)
    print(md)


def decision_analysis(probe: list[dict], morph: dict) -> dict:
    ds = p0.ce_dataset(probe, morph)
    sp, Y, base, fault = ds["space"], ds["Y"], ds["base"], ds["fault"]
    gen = np.array([ea.generator_group(b) for b in base])
    out: dict = {"n": len(Y), "bases": len(set(base)), "faults": sorted(set(fault.tolist())), "tools": ds["tools"],
                 "cf_catalogue": ds["cf_names"], "missing_nominal_morph": ds["missing_nominal_morph"],
                 "n_features": {b: len(c) for b, c in sp.blocks.items()},
                 "instances_with_a_repairing_tool": int((Y.max(1) == 1).sum()),
                 "tool_repair_rates": {t: round(float(v), 3) for t, v in zip(ds["tools"], Y.mean(0))},
                 "information_cost_rollouts": {"obs": 4, "cf": 4 * len(ds["cf_names"])}}
    # provenance: on faults that change only the controller vector, the faulty body equals the nominal base body
    nominal = sp.X[:, sp.blocks["morph"]]
    faulty = sp.X[:, sp.blocks["faulty"]]
    same = np.all(np.abs(nominal - faulty) < 1e-9, axis=1)
    out["faulty_body_equals_nominal_by_fault"] = {f: f"{int(same[fault == f].sum())}/{int((fault == f).sum())}"
                                                   for f in sorted(set(fault.tolist()))}
    has_rep = Y.max(1) == 1
    schemes = {"LOBO": base, "LOFO (fault family held out)": fault, "LOGO (generator group held out)": gen}
    preds: dict = {}
    for sname, og in schemes.items():
        block = {}
        for m, use in CE_METHODS.items():
            pr = p0.predict(sp, use, Y, base, og)
            d = p0.decision_eval(pr, Y)
            preds[(sname, m)] = (pr, d)
            ent = {"k": pr["k"], "all": p0.summarize_decision(d), "with_repairing_tool": p0.summarize_decision(d, has_rep),
                   "log_loss": round(p0.log_loss(pr["P"], Y), 4), "brier": round(p0.brier(pr["P"], Y), 4),
                   "calibration": p0.calibration(pr["P"], Y)}
            if use:
                ent["risk_coverage_sim"] = p0.risk_coverage(d, "gate_sim")
                ent["risk_coverage_benefit"] = p0.risk_coverage(d, "gate_benefit")
            block[m] = ent
        out[sname] = block
    # primary contrast and its uncertainty (cases grouped by base for every scheme)
    boot = {}
    for sname in schemes:
        di, do = preds[(sname, "interv")][1], preds[(sname, "obs_morph")][1]
        boot[sname] = {
            "interv_minus_obs_morph_value": p0.cluster_bootstrap({"a": di["v_mem"], "b": do["v_mem"]}, base,
                                                                 lambda v: v["a"].mean() - v["b"].mean()),
            "interv_delta_vs_pi0": p0.cluster_bootstrap({"a": di["v_mem"], "b": di["v_pi0"]}, base, lambda v: v["a"].mean() - v["b"].mean()),
            "obs_morph_delta_vs_pi0": p0.cluster_bootstrap({"a": do["v_mem"], "b": do["v_pi0"]}, base, lambda v: v["a"].mean() - v["b"].mean()),
            "interv_minus_obs_morph_logloss": p0.cluster_bootstrap(
                {"a": _row_ll(preds[(sname, "interv")][0]["P"], Y), "b": _row_ll(preds[(sname, "obs_morph")][0]["P"], Y)},
                base, lambda v: v["a"].mean() - v["b"].mean()),
        }
    out["bootstrap"] = boot
    # matched-coverage comparison of gates, LOBO
    rc = {}
    for m in ("obs_morph", "interv"):
        for g in ("risk_coverage_sim", "risk_coverage_benefit"):
            rc[f"{m}/{g[14:]}"] = out["LOBO"][m][g]
    out["matched_coverage_LOBO"] = rc
    # shuffled-memory control (LOBO, k fixed to the real run's per-fold k)
    rng = np.random.default_rng(p0.SEED)
    shuf = {}
    for m in ("obs_morph", "interv"):
        pr_real, d_real = preds[("LOBO", m)]
        vals = []
        for _ in range(p0.N_SHUFFLE):
            pr = p0.predict(sp, CE_METHODS[m], Y, base, base, shuffle_rng=rng, k_fixed=pr_real["k"])
            vals.append(float(p0.decision_eval(pr, Y)["v_mem"].mean()))
        real, pi0 = float(d_real["v_mem"].mean()), float(d_real["v_pi0"].mean())
        adv = real - pi0
        shuf[m] = {"real": round(real, 4), "pi0": round(pi0, 4), "shuffled_mean": round(float(np.mean(vals)), 4),
                   "shuffled_range": [round(min(vals), 4), round(max(vals), 4)],
                   "advantage_retained_by_shuffle": round((float(np.mean(vals)) - pi0) / adv, 3) if abs(adv) > 1e-12 else None}
    out["shuffled_LOBO"] = shuf
    out["hard_negative_LOBO"] = p0.hard_negative_separation(sp, Y, base, ("obs", "morph"),
                                                            {"interv": ("obs", "morph", "cf"), "obs_morph": ("obs", "morph")})
    b = boot["LOBO"]["interv_minus_obs_morph_value"]
    lofo = boot["LOFO (fault family held out)"]["interv_minus_obs_morph_value"]["est"]
    sh = shuf["interv"]["advantage_retained_by_shuffle"]
    out["primary_contrast"] = {
        "statistic": "LOBO decision value (repairs by the top tool, proxy) of interv minus obs_morph",
        "estimate": b["est"], "ci90": b["ci90"], "ci90_excludes_0": b["ci90"][0] > 0 or b["ci90"][1] < 0,
        "shuffle_loses_half_of_advantage_over_pi0": (sh is not None and sh <= 0.5),
        "lofo_same_sign": bool(np.sign(lofo) == np.sign(b["est"]) and b["est"] != 0),
    }
    pc = out["primary_contrast"]
    pc["interventional_decision_signal_present"] = bool(pc["ci90_excludes_0"] and pc["estimate"] > 0
                                                         and pc["shuffle_loses_half_of_advantage_over_pi0"] and pc["lofo_same_sign"])
    return out


def _row_ll(P, Y) -> np.ndarray:
    P = np.clip(P, p0.EPS, 1 - p0.EPS)
    return -np.mean(Y * np.log(P) + (1 - Y) * np.log(1 - P), axis=1)


def diagnostic_analysis(ident: list[dict], morph: dict) -> dict:
    ds = p0.ident_dataset(ident, morph)
    sp, y, base = ds["space"], ds["y"], ds["base"]
    C = len(p0.HDB_FAMILIES)
    gen = np.array([ea.generator_group(b) for b in base])
    out: dict = {"n": len(y), "bases": len(set(base)), "families": list(p0.HDB_FAMILIES), "cf_catalogue": ds["cf_names"],
                 "cf_missing_fraction": round(float(np.isnan(sp.X[:, sp.blocks["cf"]]).mean()), 3),
                 "n_features": {b: len(c) for b, c in sp.blocks.items()}}
    lp: dict = {}
    for sname, og in {"LOBO": base, "LOGO (generator group held out)": gen}.items():
        blk = {}
        for m, use in ID_METHODS.items():
            pr = p0.class_predict(sp, use, y, C, base, og)
            blk[m] = {"k": pr["k"], **p0.class_metrics(pr["P"], y)}
            lp[(sname, m)] = p0.per_case_logp(pr["P"], y), (pr["P"].argmax(1) == y).astype(float)
        for name, Q in ds["posterior"].items():
            blk[f"model_posterior[{name}] (no memory)"] = p0.class_metrics(Q, y)
            lp[(sname, f"post:{name}")] = p0.per_case_logp(Q, y), (Q.argmax(1) == y).astype(float)
        out[sname] = blk
    def d(a, b, i):
        return p0.cluster_bootstrap({"a": lp[("LOBO", a)][i], "b": lp[("LOBO", b)][i]}, base, lambda v: v["a"].mean() - v["b"].mean())
    out["bootstrap_LOBO"] = {"interv_minus_obs_morph_logp": d("interv", "obs_morph", 0),
                             "interv_minus_obs_morph_top1": d("interv", "obs_morph", 1),
                             "interv_minus_model_posterior_all_logp": d("interv", "post:all", 0),
                             "obs_morph_minus_prior_logp": d("obs_morph", "prior", 0)}
    rng = np.random.default_rng(p0.SEED)
    real = p0.class_predict(sp, ID_METHODS["interv"], y, C, base, base)
    sh = [p0.class_metrics(p0.class_predict(sp, ID_METHODS["interv"], y, C, base, base, shuffle_rng=rng,
                                            k_fixed=real["k"])["P"], y)["log_loss"] for _ in range(p0.N_SHUFFLE)]
    out["shuffled_interv_LOBO_log_loss"] = {"mean": round(float(np.mean(sh)), 4), "range": [round(min(sh), 4), round(max(sh), 4)]}
    return out


def stored_amortized(r: dict) -> dict:
    """Read-out of the amortized posterior's STORED outputs (arm A2 / A4 records): it cannot be re-run offline (its inputs are
    differences from nominal-design simulations on the same seeds)."""
    from creature_forge.amortized_posterior import CLASSES
    out = {}
    for f in ("hdb/artifacts/hdb/s2T_A2.jsonl", "hdb/artifacts/hdb/stage2_final/s2_transfer_A4.jsonl"):
        lp, hit, eng, n = [], [], [], 0
        for rec in ea.rows_of(os.path.join(r["vm"], f)):
            q = (rec.get("learned_last") or {}).get("proba")
            st = [tuple(x) for x in rec.get("injected_structure") or []]
            if not q or len(st) != 1 or st[0] not in CLASSES:
                continue
            n += 1
            i = CLASSES.index(st[0])
            lp.append(float(np.log(max(q[i], p0.EPS))))
            hit.append(int(np.argmax(q) == i))
            eng.append(float(np.log(max(rec.get("posterior_mass_on_injected") or 0.0, p0.EPS))))
        out[f] = {"n": n, "amortized_mean_logp_truth": round(float(np.mean(lp)), 3) if lp else None,
                  "amortized_top1": round(float(np.mean(hit)), 3) if hit else None,
                  "engine_mean_log_mass_on_truth": round(float(np.mean(eng)), 3) if eng else None,
                  "sha256": ea.sha256_file(os.path.join(r["vm"], f))}
    return out


def cited_results() -> dict:
    """Earlier results this audit relies on rather than re-deriving (hash-pinned)."""
    out = {}
    if os.path.exists(LEVEL_C):
        j = json.load(open(LEVEL_C, encoding="utf-8"))
        out["level_c_lobo"] = {"path": LEVEL_C, "sha256": ea.sha256_file(LEVEL_C), "keys": sorted(j)[:20]}
    if os.path.exists(DS1_OFFLINE):
        j = json.load(open(DS1_OFFLINE, encoding="utf-8"))
        out["ds1_offline"] = {"path": DS1_OFFLINE, "sha256": ea.sha256_file(DS1_OFFLINE),
                              "lobo": {k: {m: v[m] for m in ("log_loss", "brier", "ece")} for k, v in j["lobo"].items()},
                              "decision": j["decision"], "gate_G_a": j["gate_G_a"]}
    return out


def analysis_md(res: dict) -> str:
    L = ["# Experience-learning P0: offline signal analyses (generated by `scripts/exp_p0_audit.py analyse`)", "",
         f"Inventory sha256 {res['inventory_sha256'][:16]}; seed {res['seed']}; {res['n_boot']} base-cluster bootstrap "
         f"resamples; k grid {list(res['k_grid'])} chosen by inner leave-one-base-out. No simulation.", "",
         "HDB FULL_VERIFIED tiers: none meets D1, so no repair-decision predictor was fitted on HDB (plan §4).", ""]
    dp = res.get("decision_proxy")
    if dp:
        L += ["## Decision signal on the standardised proxy tier (causal-engineer probe set)", "",
              f"{dp['n']} instances, {dp['bases']} bases, faults {dp['faults']}; {dp['instances_with_a_repairing_tool']} have at "
              f"least one repairing tool. Value = repairs (walking >= 75 % of 8 check seeds) by the top-1 tool; pi0 = the "
              f"training-fold most frequent repairing tool. Information cost: observation {dp['information_cost_rollouts']['obs']} "
              f"rollouts, catalogue {dp['information_cost_rollouts']['cf']}.", "",
              f"Faulty body = nominal body, by fault (provenance check): {dp['faulty_body_equals_nominal_by_fault']}.", ""]
        for sname in ("LOBO", "LOFO (fault family held out)", "LOGO (generator group held out)"):
            L += [f"### {sname}", ""]
            rows = []
            for m, e in dp[sname].items():
                a, w = e["all"], e["with_repairing_tool"]
                rows.append([m, a["value_mem"], a["value_pi0"], a["delta_vs_pi0"], a["p_plus"], a["p_minus"], a["regret_mem"],
                             w["value_mem"], e["log_loss"], e["brier"], e["calibration"]["intercept"], e["calibration"]["slope"]])
            L += _t(rows, ["method", "value", "pi0", "delta", "p+", "p-", "regret", "top-1 (>=1 repairing)", "log loss",
                           "Brier", "calib a", "calib b"])
            L.append("")
        L += ["### Uncertainty (base-cluster bootstrap)", ""]
        rows = []
        for sname, bb in dp["bootstrap"].items():
            for k, v in bb.items():
                rows.append([sname, k, v["est"], v["ci90"], v["ci95"]])
        L += _t(rows, ["scheme", "statistic", "estimate", "90 % CI", "95 % CI"])
        L += ["", "### Matched-coverage risk-coverage (LOBO): value / negative-transfer rate", ""]
        cov = [x["coverage"] for x in next(iter(dp["matched_coverage_LOBO"].values()))]
        rows = [[g] + [f"{x['value']:.3f} / {x['negative_transfer']:.3f}" for x in v] for g, v in dp["matched_coverage_LOBO"].items()]
        L += _t(rows, ["method/gate"] + [str(c) for c in cov])
        L += ["", "### Controls", ""]
        for m, s in dp["shuffled_LOBO"].items():
            L.append(f"- Shuffled memory, {m}: real {s['real']}, pi0 {s['pi0']}, shuffled mean {s['shuffled_mean']} "
                     f"(range {s['shuffled_range']}); share of the advantage over pi0 retained by shuffling: {s['advantage_retained_by_shuffle']}.")
        hn = dp["hard_negative_LOBO"]
        L.append(f"- Hard negatives ({hn['n_queries']} queries): pairs separated by interv {hn['interv']['est']} "
                 f"{hn['interv']['ci90']}, by obs_morph {hn['obs_morph']['est']} {hn['obs_morph']['ci90']} (0.5 = chance); "
                 f"difference {hn['interv_minus_obs_morph']['est']} {hn['interv_minus_obs_morph']['ci90']}.")
        pc = dp["primary_contrast"]
        L += ["", f"**Primary contrast:** {pc['statistic']}: {pc['estimate']} (90 % CI {pc['ci90']}). CI excludes 0: "
              f"{pc['ci90_excludes_0']}; shuffle loses >= half the advantage: {pc['shuffle_loses_half_of_advantage_over_pi0']}; "
              f"same sign under LOFO: {pc['lofo_same_sign']}. **Interventional decision signal present (proxy): "
              f"{pc['interventional_decision_signal_present']}.**", ""]
    dg = res["diagnostic_hdb"]
    L += ["## HDB diagnostic precondition (fault-family prediction; not a decision result)", "",
          f"{dg['n']} eligible identifiability instances, {dg['bases']} bases; counterfactual cells missing (design bounds): "
          f"{dg['cf_missing_fraction']}.", ""]
    for sname in ("LOBO", "LOGO (generator group held out)"):
        L += [f"### {sname}", ""]
        L += _t([[m, e["log_loss"], e["brier"], e["top1"], e["ece"], e["selective_acc"]] for m, e in dg[sname].items()],
                ["method", "log loss", "Brier", "top-1", "ECE", "selective accuracy by coverage"])
        L.append("")
    L += _t([[k, v["est"], v["ci90"], v["ci95"]] for k, v in dg["bootstrap_LOBO"].items()],
            ["LOBO contrast (mean per case)", "estimate", "90 % CI", "95 % CI"])
    s = dg["shuffled_interv_LOBO_log_loss"]
    L += ["", f"Shuffled labels, interv: log loss {s['mean']} (range {s['range']}).", "",
          "## Stored amortized-posterior outputs (cannot be re-run offline)", ""]
    L += _t([[f, v["n"], v["amortized_mean_logp_truth"], v["amortized_top1"], v["engine_mean_log_mass_on_truth"]]
             for f, v in res["stored_amortized"].items()], ["record file", "n", "amortized mean log p(truth)", "amortized top-1",
                                                             "engine mean log mass on truth"])
    c = res["cited"].get("ds1_offline")
    if c:
        L += ["", f"Cited (not re-run): DS-1 offline belief-space case attention on level-P support (`{c['path']}`, sha256 "
              f"{c['sha256'][:16]}): LOBO {c['lobo']['case_attention']}; decision {c['decision']}; G-a {c['gate_G_a']['passed']}."]
    return "\n".join(L) + "\n"


